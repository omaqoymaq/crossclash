#!/usr/bin/env python3
"""Exports generator/data/common-words.txt: common English words (2-10 letters)
ranked by frequency, from the `wordfreq` package (pip install wordfreq).

wordfreq data is licensed CC BY-SA 4.0 (Robyn Speer et al.); the exported list
keeps that licence. Only the word list is used: no text from wordfreq ends up
in the game except the answer words themselves.
"""
import re, sys
from pathlib import Path
from wordfreq import top_n_list, zipf_frequency

out = Path(__file__).resolve().parent.parent / 'data' / 'common-words.txt'
n = int(sys.argv[1]) if len(sys.argv) > 1 else 60000
lines = ['# word<TAB>zipf frequency. Source: wordfreq (CC BY-SA 4.0). Generated by tools/export-common-words.py']
for w in top_n_list('en', n):
    if re.fullmatch('[a-z]{2,10}', w):
        lines.append(f'{w}\t{zipf_frequency(w, "en"):.2f}')
out.write_text('\n'.join(lines) + '\n')
print(f'{len(lines) - 1} words -> {out}')
